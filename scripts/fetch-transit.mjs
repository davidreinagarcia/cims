#!/usr/bin/env node
/** @file Fetches Georgia Tech bus routes and stops from the official live tracker (bus.gatech.edu) into src/data/transit.geojson (T-42). */
// Usage: node scripts/fetch-transit.mjs [--from <routes.json>]
//   One GET to the tracker's own route endpoint (the data bus.gatech.edu draws). Writes route lines (decoded
//   from the tracker's encoded polylines, never inferred from stops) and stops (one per physical stop, with the
//   routes that serve it). --from reuses a saved response. Re-run when PTS changes routes (each semester).
//   The older wrapper gtbuses.herokuapp.com is dead for GT (NextBus feed ended 2019): don't use it.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { execSync } from "node:child_process";

const ROOT = execSync("git rev-parse --show-toplevel").toString().trim();
const OUT = join(ROOT, "src/data/transit.geojson");
const SOURCE_URL = "https://bus.gatech.edu/";
const ENDPOINT = "https://bus.gatech.edu/Services/JSONPRelay.svc/GetRoutesForMapWithScheduleWithEncodedLine";

/** Downloads the tracker's route list, or reads it from --from <file>. */
async function load() {
  const i = process.argv.indexOf("--from");
  if (i > 0) return JSON.parse(readFileSync(process.argv[i + 1], "utf8"));
  const res = await fetch(ENDPOINT, { headers: { "User-Agent": "cims-hackathon (github.com/davidreinagarcia/cims)" } });
  if (!res.ok) throw new Error(`Tracker HTTP ${res.status}`);
  return res.json();
}

/** Decodes a Google encoded polyline (precision 5) into [lng, lat] pairs. */
function decodePolyline(str) {
  const out = [];
  let i = 0, lat = 0, lng = 0;
  const next = () => {
    let result = 0, shift = 0, b;
    do { b = str.charCodeAt(i++) - 63; result |= (b & 0x1f) << shift; shift += 5; } while (b >= 0x20);
    return result & 1 ? ~(result >> 1) : result >> 1;
  };
  while (i < str.length) { lat += next(); lng += next(); out.push([lng / 1e5, lat / 1e5]); }
  return out;
}

const clean = (s) => (s ?? "").replace(/ /g, " ").replace(/\s+/g, " ").trim();
const round = (n) => Math.round(n * 1e6) / 1e6;

const routes = await load();
// The body must be the route array: an HTTP 200 with an error object is not data.
if (!Array.isArray(routes) || !routes.some((r) => r.EncodedPolyline)) {
  console.error("Tracker returned no routes. Nothing written.");
  process.exit(1);
}

const today = new Date().toISOString().slice(0, 10);
const provenance = { source_url: SOURCE_URL, fetched_at: today, verified_at: null, verified_by: null };
const features = [];
const stops = new Map();

for (const r of routes.filter((x) => x.IsVisibleOnMap && x.EncodedPolyline).sort((a, b) => a.RouteID - b.RouteID)) {
  const name = clean(r.Description);
  features.push({
    type: "Feature",
    properties: { id: `route-${r.RouteID}`, kind: "route", category: "transport", route_id: r.RouteID, name, service_hours: clean(r.InfoText.replace(/\n/g, " · ")).replace(/ ·$/, "") || null, ...provenance },
    geometry: { type: "LineString", coordinates: decodePolyline(r.EncodedPolyline) },
  });
  for (const s of r.Stops ?? []) {
    // AddressID is the physical stop; several routes share it.
    const stop = stops.get(s.AddressID) ?? { name: clean(s.Description || s.Name), at: [round(s.Longitude), round(s.Latitude)], routes: [] };
    if (!stop.routes.includes(name)) stop.routes.push(name);
    stops.set(s.AddressID, stop);
  }
}
for (const [id, s] of [...stops].sort((a, b) => a[0] - b[0])) {
  features.push({
    type: "Feature",
    properties: { id: `stop-${id}`, kind: "stop", category: "transport", name: s.name, routes: s.routes.join(", "), ...provenance },
    geometry: { type: "Point", coordinates: s.at },
  });
}

const out = {
  type: "FeatureCollection",
  _note: "Generated by scripts/fetch-transit.mjs from the official GT bus tracker (bus.gatech.edu). Don't hand-edit: re-run.",
  attribution: "Georgia Tech Parking & Transportation Services (bus.gatech.edu)",
  generated_at: today,
  features,
};
writeFileSync(OUT, JSON.stringify(out) + "\n");
const nRoutes = features.filter((f) => f.properties.kind === "route").length;
console.log(`transit.geojson: ${nRoutes} routes (${features.filter((f) => f.properties.kind === "route").map((f) => f.properties.name).join(", ")}) · ${stops.size} stops · ${(JSON.stringify(out).length / 1024).toFixed(0)} KB`);
