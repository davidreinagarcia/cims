#!/usr/bin/env node
/** @file Generates folder INDEX.md files, the global INDEX.md and docs/FUNCTIONS.md from the repo. Zero deps. */
// Usage: node scripts/gen-index.mjs [--check] [--quiet] [--json] [--files-from <file>]
//   (no flag)  regenerate everything in place
//   --check    don't write; exit 1 if anything is stale or a relative link is broken (CI)
//   --json     print a machine-readable report (used by the Claude Stop hook)
// Hand-written text OUTSIDE the AUTO markers is preserved. Never edit inside them.
import { execSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, posix, basename, extname } from "node:path";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const args = new Set(process.argv.slice(2));
const CHECK = args.has("--check");
const QUIET = args.has("--quiet");
const JSON_OUT = args.has("--json");

const START = "<!-- AUTO:START — generated by scripts/gen-index.mjs; edit the text above this line only -->";
const END = "<!-- AUTO:END -->";
const FUNCTIONS = "docs/FUNCTIONS.md";
// Folders that need no index: config, plus whatever is listed in /.indexignore (one folder per line,
// "#" comments). Add raw uploads (images, prompts, scratch notes) there instead of editing this script.
const SKIP_DIRS = [".claude", ".githooks"];
try {
  for (const line of readFileSync(join(ROOT, ".indexignore"), "utf8").split("\n")) {
    const d = line.replace(/#.*/, "").trim().replace(/\/+$/, "");
    if (d) SKIP_DIRS.push(d);
  }
} catch {}
const CODE = new Set([".ts", ".tsx", ".js", ".mjs", ".cjs"]);
const MAX = 110;

// ---------- file list (respects .gitignore, includes untracked) ----------
// --files-from accepts a newline-separated inventory when git use is disallowed.
const inventoryAt = process.argv.indexOf("--files-from");
const inventory = inventoryAt > 0
  ? readFileSync(process.argv[inventoryAt + 1], "utf8")
  : execSync("git ls-files -co --exclude-standard", { cwd: ROOT }).toString();
const files = inventory.split("\n").filter(Boolean)
  .filter((f) => existsSync(join(ROOT, f)))
  .filter((f) => !isGenerated(f))
  .filter((f) => !SKIP_DIRS.some((d) => f.startsWith(d + "/")))
  .sort();

function isGenerated(f) {
  return basename(f) === "INDEX.md" || f === FUNCTIONS;
}

const read = (f) => readFileSync(join(ROOT, f), "utf8");
const clip = (s) => {
  s = s.replace(/\s+/g, " ").trim();
  return s.length > MAX ? s.slice(0, MAX - 1).trimEnd() + "…" : s;
};
const stripMd = (s) => s.replace(/!?\[([^\]]*)\]\([^)]*\)/g, "$1").replace(/[*_`>#]/g, "").trim();

// ---------- summaries ----------
function mdSummary(text) {
  const m = text.match(/<!--\s*summary:\s*(.+?)\s*-->/);
  if (m) return clip(m[1]);
  let inFence = false;
  for (const raw of text.split("\n")) {
    const l = raw.trim();
    if (l.startsWith("```")) { inFence = !inFence; continue; }
    if (inFence || !l || l.startsWith("#") || l.startsWith("|") || l.startsWith("<!--") || /^[-*_]{3,}$/.test(l)) continue;
    const s = stripMd(l.replace(/^[-*]\s+(\[.\]\s+)?/, ""));
    if (s.length > 15) return clip(s);
  }
  return "";
}

function codeSummary(text) {
  const file = text.match(/\/\*\*\s*@file\s+([\s\S]*?)\*\//);
  if (file) return clip(file[1].replace(/^\s*\*\s?/gm, ""));
  const lines = text.split("\n");
  let i = lines[0]?.startsWith("#!") ? 1 : 0;
  const out = [];
  for (; i < lines.length; i++) {
    const m = lines[i].match(/^\s*\/\/\s?(.*)$/);
    if (!m) break;
    out.push(m[1]);
  }
  return out.length ? clip(out.join(" ")) : "";
}

function shSummary(text) {
  const l = text.split("\n").find((x, i) => (i > 0 || !x.startsWith("#!")) && /^#\s?\S/.test(x));
  return l ? clip(l.replace(/^#\s?/, "")) : "";
}

function jsonSummary(f, text) {
  try {
    const j = JSON.parse(text);
    if (basename(f) === "package.json") return `npm manifest · scripts: ${Object.keys(j.scripts ?? {}).join(", ")}`;
    if (basename(f) === "package-lock.json") return "npm lockfile (don't read; don't hand-edit)";
    if (basename(f).startsWith("tsconfig")) return "TypeScript compiler config";
    const note = j._note ?? j.description ?? "";
    if (j.type === "FeatureCollection") return clip(`GeoJSON, ${j.features?.length ?? 0} features${note ? " · " + note : ""}`);
    return clip(note || (Array.isArray(j) ? `JSON array, ${j.length} items` : `JSON: ${Object.keys(j).slice(0, 6).join(", ")}`));
  } catch { return ""; }
}

function summarize(f) {
  if (basename(f) === "package-lock.json") return "npm lockfile (don't read; don't hand-edit)";
  const ext = extname(f).toLowerCase();
  if ([".png", ".jpg", ".jpeg", ".gif", ".webp", ".ico"].includes(ext)) return "image";
  if (ext === ".svg") return "SVG image";
  let text;
  try { text = read(f); } catch { return ""; }
  if (basename(f) === ".gitignore") return "Files and folders git ignores";
  if (ext === ".md") return mdSummary(text);
  if (CODE.has(ext)) return codeSummary(text);
  if (ext === ".sh" || ext === ".conf" || ext === ".yml" || ext === ".yaml" || basename(f).startsWith(".")) return shSummary(text);
  if (ext === ".json" || ext === ".geojson") return jsonSummary(f, text);
  if (ext === ".css") { const m = text.match(/\/\*\s*([\s\S]*?)\*\//); return m ? clip(m[1]) : ""; }
  if (ext === ".html") { const m = text.match(/<title>(.*?)<\/title>/i); return m ? `HTML entry · ${m[1]}` : "HTML entry"; }
  return "";
}

// ---------- exports (function registry) ----------
function jsdocBefore(lines, idx) {
  let j = idx - 1;
  while (j >= 0 && lines[j].trim() === "") j--;
  if (j < 0 || !lines[j].trim().endsWith("*/")) {
    const block = [];
    for (let c; j >= 0 && (c = lines[j].match(/^\s*\/\/\s?(.*)$/)); j--) block.unshift(c[1]);
    return block.length ? clip(block.join(" ")) : "";
  }
  const block = [];
  for (; j >= 0; j--) { block.unshift(lines[j]); if (lines[j].includes("/**")) break; }
  const body = block.join("\n").replace(/\/\*\*|\*\//g, "").replace(/^\s*\*\s?/gm, "").split("\n")
    .map((s) => s.trim()).filter((s) => s && !s.startsWith("@"));
  return body.length ? clip(body[0]) : "";
}

function exportsOf(f) {
  if (!CODE.has(extname(f)) || f.startsWith("scripts/")) return [];
  const lines = read(f).split("\n");
  const out = [];
  lines.forEach((l, i) => {
    let m;
    if ((m = l.match(/^export\s+(default\s+)?(async\s+)?function\s+(\w+)\s*(<[^>]*>)?\s*(\([^)]*\))?/))) {
      const isComp = f.endsWith(".tsx") && /^[A-Z]/.test(m[3]);
      out.push({ name: m[3], kind: isComp ? "component" : "function", sig: m[5] ? compactSig(m[5]) : "(…)", line: i + 1, doc: jsdocBefore(lines, i) });
    } else if ((m = l.match(/^export\s+const\s+(\w+)\s*(?::[^=]+)?=\s*(async\s+)?(\([^)]*\)|\w+)\s*(?::[^=]+)?=>/))) {
      out.push({ name: m[1], kind: /^[A-Z]/.test(m[1]) && f.endsWith(".tsx") ? "component" : "function", sig: compactSig(m[3].startsWith("(") ? m[3] : `(${m[3]})`), line: i + 1, doc: jsdocBefore(lines, i) });
    } else if ((m = l.match(/^export\s+(const|let)\s+(\w+)/))) {
      out.push({ name: m[2], kind: "const", sig: "", line: i + 1, doc: jsdocBefore(lines, i) });
    } else if ((m = l.match(/^export\s+(interface|type|enum|class)\s+(\w+)/))) {
      out.push({ name: m[2], kind: m[1] === "class" ? "class" : "type", sig: "", line: i + 1, doc: jsdocBefore(lines, i) });
    }
  });
  return out;
}
const compactSig = (s) => clip(s.replace(/\s+/g, " ").replace(/:\s*[^,)]+/g, "")); // names only: cheap to read

// ---------- folder tree ----------
const dirs = new Set([""]);
for (const f of files) {
  let d = dirname(f);
  while (d !== "." && !dirs.has(d)) { dirs.add(d); d = dirname(d); }
}
const dirList = [...dirs].filter((d) => !SKIP_DIRS.some((s) => d === s || d.startsWith(s + "/"))).sort();
const childrenDirs = (d) => dirList.filter((x) => x && posix.dirname(x) === (d || "."));
const childFiles = (d) => files.filter((f) => posix.dirname(f) === (d || "."));
const idxPath = (d) => (d ? `${d}/INDEX.md` : "INDEX.md");

function handPart(path, fallbackTitle, fallbackDesc) {
  const p = join(ROOT, path);
  if (existsSync(p)) {
    const t = readFileSync(p, "utf8");
    const i = t.indexOf("<!-- AUTO:START");
    if (i >= 0) return t.slice(0, i).trimEnd();
  }
  return `# ${fallbackTitle}\n\n${fallbackDesc}`;
}
const PLACEHOLDER = "<!-- TODO(agent): one line describing what this folder is for. -->";
function dirDescription(d) {
  const hand = handPart(idxPath(d), "", "");
  const line = hand.split("\n").map((s) => s.trim()).find((s) => s && !s.startsWith("#") && !s.startsWith("<!--") && !s.startsWith(">"));
  return line ? clip(stripMd(line)) : "";
}

const report = { stale: [], brokenLinks: [], missingSummaries: [], missingDirDesc: [], duplicates: [], missingDocs: [] };
const outputs = new Map();

for (const d of dirList.filter(Boolean)) {
  const lines = [START, ""];
  const sub = childrenDirs(d);
  if (sub.length) {
    lines.push("**Folders**", "");
    for (const s of sub) lines.push(`- [\`${basename(s)}/\`](${basename(s)}/INDEX.md): ${dirDescription(s) || "_no description yet_"}`);
    lines.push("");
  }
  const fl = childFiles(d);
  if (fl.length) {
    lines.push("**Files**", "");
    for (const f of fl) {
      const s = summarize(f);
      if (!s && !/\.(png|jpe?g|gif|webp|ico|svg)$/i.test(f) && !f.endsWith("package-lock.json")) report.missingSummaries.push(f);
      const ex = exportsOf(f).filter((e) => e.kind !== "type").map((e) => `\`${e.name}\``);
      lines.push(`- [\`${basename(f)}\`](${basename(f)}): ${s || "_no summary_"}${ex.length ? ` · exports ${ex.join(", ")}` : ""}`);
    }
    lines.push("");
  }
  lines.push(END, "");
  const hand = handPart(idxPath(d), `${d}/`, PLACEHOLDER);
  if (!dirDescription(d)) report.missingDirDesc.push(d);
  outputs.set(idxPath(d), `${hand}\n\n${lines.join("\n")}`);
}

// ---------- global INDEX.md ----------
{
  const g = [START, "", "**Map** (open a folder's INDEX.md, not the folder):", ""];
  const walk = (d, depth) => {
    for (const s of childrenDirs(d)) {
      g.push(`${"  ".repeat(depth)}- [\`${s}/\`](${s}/INDEX.md): ${dirDescription(s) || "_no description yet_"}`);
      walk(s, depth + 1);
    }
  };
  walk("", 0);
  g.push("", "**Root files**", "");
  for (const f of childFiles("")) g.push(`- [\`${f}\`](${f}): ${summarize(f) || "_no summary_"}`);
  g.push("", `**Function & type registry:** [\`${FUNCTIONS}\`](${FUNCTIONS})`, "", END, "");
  const hand = handPart("INDEX.md", "INDEX", "Global map of the repo.");
  outputs.set("INDEX.md", `${hand}\n\n${g.join("\n")}`);
}

// ---------- docs/FUNCTIONS.md ----------
{
  const all = [];
  for (const f of files) for (const e of exportsOf(f)) {
    all.push({ ...e, file: f });
    if (!e.doc) report.missingDocs.push(`${f}:${e.line} ${e.name}`);
  }
  const byName = new Map();
  for (const e of all.filter((e) => e.kind !== "type")) {
    const k = e.name.toLowerCase().replace(/[^a-z0-9]/g, "");
    byName.set(k, [...(byName.get(k) ?? []), e]);
  }
  for (const [, list] of byName) if (list.length > 1) report.duplicates.push(list.map((e) => `${e.name} (${e.file}:${e.line})`).join(" ↔ "));

  const sec = (title, pred) => {
    const rows = all.filter(pred);
    if (!rows.length) return [];
    const out = [`### ${title}`, ""];
    for (const e of rows) out.push(`- \`${e.name}${e.sig}\` [${e.file}:${e.line}](../${e.file}#L${e.line})${e.doc ? `: ${e.doc}` : ""}`);
    return [...out, ""];
  };
  const isShared = (e) => /^src\/(lib|state|hooks)\//.test(e.file);
  const lines = [START, "",
    ...sec("Shared helpers (`src/lib`, `src/state`, `src/hooks`): reuse these first", (e) => isShared(e) && e.kind !== "type" && e.kind !== "component"),
    ...sec("Types & contracts", (e) => e.kind === "type"),
    ...sec("Components", (e) => e.kind === "component"),
    ...sec("Other exported functions & constants", (e) => !isShared(e) && e.kind !== "type" && e.kind !== "component"),
    "### Possible duplicates", "",
    ...(report.duplicates.length ? report.duplicates.map((d) => `- ⚠️ ${d}`) : ["_None detected._"]),
    "", END, ""];
  const hand = handPart(FUNCTIONS, "FUNCTIONS", "Registry of exported functions.");
  outputs.set(FUNCTIONS, `${hand}\n\n${lines.join("\n")}`);
}

// ---------- write / check ----------
for (const [p, content] of outputs) {
  const abs = join(ROOT, p);
  const cur = existsSync(abs) ? readFileSync(abs, "utf8") : null;
  if (cur === content) continue;
  report.stale.push(p);
  if (!CHECK) writeFileSync(abs, content);
}

// ---------- relative link check (all markdown) ----------
const mdFiles = [...files.filter((f) => f.endsWith(".md")), ...outputs.keys()];
for (const f of mdFiles) {
  const text = outputs.get(f) ?? read(f);
  const noCode = text.replace(/```[\s\S]*?```/g, "").replace(/`[^`]*`/g, "");
  for (const m of noCode.matchAll(/\]\(([^)\s]+)\)/g)) {
    const target = m[1].split("#")[0];
    if (!target || /^[a-z]+:/i.test(target) || target.startsWith("<") || /XXXX|NNNN/.test(target)) continue;
    const p = posix.normalize(posix.join(posix.dirname(f), target));
    if (!existsSync(join(ROOT, p)) && !outputs.has(p)) report.brokenLinks.push(`${f} → ${m[1]}`);
  }
}

if (JSON_OUT) { console.log(JSON.stringify(report)); process.exit(0); }
if (!QUIET || CHECK) {
  const say = (t, l) => l.length && console.log(`${t}:\n  ${l.join("\n  ")}`);
  if (CHECK) say("Stale generated files (run `npm run index`)", report.stale);
  else if (!QUIET) console.log(report.stale.length ? `Updated ${report.stale.length} index file(s).` : "Indexes up to date.");
  say("Broken relative links", report.brokenLinks);
  if (!QUIET) {
    say("Files without a one-line summary", report.missingSummaries);
    say("Folders without a description", report.missingDirDesc);
    say("Possible duplicate functions", report.duplicates);
    if (report.missingDocs.length) console.log(`Exports without a JSDoc line: ${report.missingDocs.length} (run with --json for the list)`);
  }
}
if (CHECK && (report.stale.length || report.brokenLinks.length)) process.exit(1);
